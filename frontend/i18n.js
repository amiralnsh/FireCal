var LANG = navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
try {
  var savedLang = localStorage.getItem("lang");
  if (savedLang === "ru" || savedLang === "en") LANG = savedLang;
} catch (err) {}
var sharedLang = new URLSearchParams(location.hash.slice(1)).get("lg");
if (sharedLang === "ru" || sharedLang === "en") LANG = sharedLang;

// t("key") или t("key", { n: 5 }) подставляет {n}
function t(key, vars) {
  var s = I18N[LANG][key];
  if (s === undefined) s = I18N.ru[key];
  if (s === undefined) return key;
  if (vars && typeof s === "string") {
    Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(String(vars[k])); });
  }
  return s;
}

// применяет перевод ко всем элементам с data-i18n, data-i18n-title, data-i18n-ph, data-i18n-q
function applyStaticLang() {
  document.documentElement.lang = LANG;
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (e) {
    e.textContent = t(e.getAttribute("data-i18n"));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-title]"), function (e) {
    e.title = t(e.getAttribute("data-i18n-title"));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-aria]"), function (e) {
    e.setAttribute("aria-label", t(e.getAttribute("data-i18n-aria")));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-ph]"), function (e) {
    e.placeholder = t(e.getAttribute("data-i18n-ph"));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-q]"), function (e) {
    e.textContent = t(e.getAttribute("data-i18n-q"));
    e.setAttribute("data-q", t(e.getAttribute("data-i18n-q")));
  });
  var m1 = document.querySelectorAll("#monthRow span");
  Array.prototype.forEach.call(m1, function (e, i) { e.textContent = t("mon1")[i]; });
  document.title = "FireCal";
}
